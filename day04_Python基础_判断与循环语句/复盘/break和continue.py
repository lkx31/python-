# 场景一：如果吃的过程中，吃完第三个吃饱了，则不需要再吃第4个和第5个苹果，即是吃苹果的动作停for i in range
# 止，这里就是break控制循环流程，即终止此循环。
for i in range(1,6):
    print(f"我开始吃第{i}个苹果")
    if i ==3:
        print(f"我吃完第{i}个苹果，吃饱了")
        break
    print(f"我吃完第{i}个苹果")
# 场景二：如果吃的过程中，吃到第三个吃出一个大虫子...,是不是这个苹果就不吃了，开始吃第四个苹果，这里就是continue控制循环流程，即退出当前一次循环继而执行下一次循环代码。
# 在使用continue的时候, 一定要注意 记得提前先更新计数器, 否则会导致无法更新计数器 出现 一直处于跳出的状态不断地循环(无休止)
for z in range(1,6):
    print(f"我开始吃第{z}个苹果")
    if z == 3:
        print(f"我吃完第{z}个苹果，吃到虫子了")
        continue
    print(f"我吃完第{z}个苹果")