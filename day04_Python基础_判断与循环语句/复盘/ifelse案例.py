"""
    要求键盘录入一个成绩,请进行以下处理:
        当用户的成绩 >= 90 分的时候, 告知用户成绩优秀
        当用户的成绩 在75分 ~ 89分  告知用户 成绩良好
        当用户的成绩在 60~74分 告知用户 成绩及格
        当用户的成绩在 60分以下的时候, 告知用户 成绩不及格
"""
source=int(input("请输入成绩"))
if source>=90:
    print("优秀")
elif source>=75:
    print("良好1")
elif source>=60:
    print("及格")
else:
    print("不及格")