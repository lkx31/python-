# 酒精含量大于或等于 20mg/100ml 为酒驾；酒精含量大于或等于 80mg/100ml 为醉驾。
# 编写 Python 程序判断是否为酒后驾车。
# 首先分析一下问题，是不是第一和没喝酒是否小于20mg,喝酒了和没喝酒，那么喝酒i又分醉驾和酒驾两个
#那么设一个int型的input方法对吧
mg=int(input("请输入你血液中酒精含量"))
if mg>20:
    if mg>20 and mg<80:
        print("酒驾")
    else:
        print("醉驾")
