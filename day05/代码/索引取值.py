# 演示 字符串切片
"""
    切片的格式:
        序列名称[起始值:结束值:步长]

        起始值 : 从什么位置开始截取, 默认为 0
        结束值 : 到什么位置结束,默认为序列的最后
        步长:  表示截取的上, 每一个元素和下一个元素中间相差几个索引值  默认为 1

        索引: 支持 正索引 也支持 负索引
            正索引: 从左往右   0   左边的第一个
            负索引: 从右往左   -1  右边的最后一个
"""
# 案例一:
numstr = '0123456789'
# 1、从2到5开始切片，步长为1
print(numstr[2:5])  # 2 3 4
# 2、只有结尾的字符串切片：代表从索引为0开始，截取到索引为5的位置（不包含索引为5的数据）
print(numstr[:5])
# 3、只有开头的字符串切片：代表从起始位置开始(例如 1)，已知截取到字符串的结尾
print(numstr[1:])  # 注意 一定要带上 :  否则 会认为获取指定索引下的数据
# 4、获取或拷贝整个字符串
print(numstr[:])  # 表示复制了一个新的字符串
# 5、调整步阶：类似求偶数
print(numstr[::2])
# 6、把步阶设置为负整数：类似字符串翻转
print(numstr[::-1])  # 从右往左
# 7、起始位置与结束位置都是负数
print(numstr[-2:-5:-1]) # 默认是从左往右获取数据, 如果 步长为负数 表示 从右往左获取
# 8、结束字符为负数，如截取012345678
print(numstr[0:-1])