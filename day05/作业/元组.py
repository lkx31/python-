# 编写一个程序来提取嵌套元组中的唯一元素。
# 例如: 在嵌套元组((1,2,3),(2,4,6),(2,3,5))中, 2重复出现了3次，3重复出现了2次，但我们的输出列表只会包含2、3一次。
# 即：[1, 2, 3, 4, 5, 6]
list1 = []
t = ((1, 2, 3),
     (2, 4, 6),
     (2, 3, 5)
     )
for t1 in t:
    for t2 in t1:
        if t2 in list1:
            pass
        else:
            list1.append(t2)
print(list1
      )

